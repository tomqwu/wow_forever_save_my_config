local locales = {enUS=enUS,enGB=enUS,zhCN=zhCN,zhTW=zhTW}
local locale = GetLocale and GetLocale() or 'enUS'
local selected = locales[locale] or enUS
NS.Locale,NS.Locales=locale,locales
NS.L=selected==enUS and enUS or setmetatable(selected,{__index=enUS})
function NS.Text(key,...)
    local value=NS.L[key] or key
    if select('#',...)>0 then return string.format(value,...) end
    return value
end
